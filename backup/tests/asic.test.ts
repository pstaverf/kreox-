import assert from 'node:assert/strict';
import { test } from 'node:test';
import { game } from '../src/config/game.js';
import { parseCommand } from '../src/handlers/commands.js';
import { buildKeyboard } from '../src/handlers/keyboards.js';
import { GameService } from '../src/services/game.js';
import { itemDetails } from '../src/services/item-texts.js';
import type { Command, GameInput } from '../src/types/game.js';
import { MemoryDatabase } from './memory.js';

test('ASIC is an admin-granted permanent item, displayed only when available and starts the farm for exactly nine hours', async () => {
  const db = new MemoryDatabase();
  db.time = new Date('2026-11-05T15:40:56.000Z');
  let service = new GameService(db);
  let sequence = 0;
  const send = (command: Command, extra: Partial<GameInput> = {}, vkId = 1) => service.handle({ eventId: `asic-${sequence++}`, vkId, command, ...extra }, async () => 'Игрок');
  await send({ kind: 'profile' });
  const without = await send({ kind: 'mining' });
  assert.equal(without.keyboard.kind, 'mining');
  assert.doesNotMatch(without.text, /использовать предмет/u);
  assert.equal((await send({ kind: 'mining_asic' })).text, '⚠️ У вас нет данного предмета!');
  assert.equal((await send(parseCommand('!giveitem @id1 10', undefined), {}, 888801846)).text, 'Done.');
  assert.equal(db.state.items.filter(item => item.vkId === 1 && item.kind === 'asic').length, 1);
  assert.equal(itemDetails('asic', 1), '📒 Предмет "📼 Асик" (x1):\n\n📋 Запускает вашу ферму на 9 часов');
  assert.match((await send({ kind: 'item_use', itemKind: 'asic' })).text, /Майнинг/u);
  const view = await send({ kind: 'mining' });
  assert.match(view.text, /\n\n💡 Вы можете использовать предмет для фермы!$/u);
  assert.deepEqual(view.keyboard, { kind: 'mining', asic: true });
  const keyboard: unknown = JSON.parse(buildKeyboard(view.keyboard).toString());
  assert.ok(keyboard && typeof keyboard === 'object' && 'buttons' in keyboard);
  const rows = (keyboard as { buttons: { action: { label: string; payload: string } }[][] }).buttons;
  assert.equal(rows[0]?.[0]?.action.label, 'Асик');
  assert.deepEqual(parseCommand('Асик', JSON.parse(rows[0]?.[0]?.action.payload ?? '{}')), { kind: 'mining_asic' });
  assert.equal(rows.length, 3);

  const activation = { eventId: 'asic-first-activation', vkId: 1, command: { kind: 'mining_asic' } } as const;
  const started = await service.handle(activation, async () => 'Игрок');
  assert.equal(started.text, '💽 Ваша ферма активирована до 6 ноября 2026 03:40:56!');
  assert.equal(db.player().mining?.activeUntil.getTime(), db.time.getTime() + game.mining.asicDurationMs);
  assert.equal(db.state.items.filter(item => item.vkId === 1 && item.kind === 'asic').length, 1);
  const activeUntil = db.player().mining?.activeUntil.getTime();
  assert.equal((await send({ kind: 'mining_asic' })).text, '💽 Ваша ферма еще работает!');
  assert.equal(db.player().mining?.activeUntil.getTime(), activeUntil);
  db.time = new Date(db.time.getTime() + game.mining.asicDurationMs);
  service = new GameService(db);
  assert.deepEqual(await service.handle(activation, async () => 'Игрок'), started);
  assert.equal(db.player().mining?.activeUntil.getTime(), activeUntil);
  const second = await send({ kind: 'mining_asic' });
  assert.match(second.text, /^💽 Ваша ферма активирована до/u);
  assert.equal(db.player().mining?.activeUntil.getTime(), db.time.getTime() + game.mining.asicDurationMs);
  assert.equal(db.player().mining?.balance, 9 * game.mining.initialRate);
  assert.equal(db.state.items.filter(item => item.vkId === 1 && item.kind === 'asic').length, 1);
});

test('ASIC cannot be forged or used while the only copy is reserved in a sale', async () => {
  const db = new MemoryDatabase();
  const service = new GameService(db);
  let sequence = 0;
  const send = (command: Command) => service.handle({ eventId: `asic-reserved-${sequence++}`, vkId: 1, command }, async () => 'Игрок');
  await send({ kind: 'profile' });
  await db.transaction(async store => { assert.equal(await store.grantItems(1, 'asic', 1), true); });
  const item = db.state.items[0];
  assert.ok(item);
  item.reservedUntil = new Date(db.time.getTime() + 60_000);
  const view = await send({ kind: 'mining' });
  assert.deepEqual(view.keyboard, { kind: 'mining' });
  assert.doesNotMatch(view.text, /использовать предмет/u);
  assert.equal((await send({ kind: 'mining_asic' })).text, '⚠️ У вас нет данного предмета!');
  assert.equal(db.player().mining?.activeUntil.getTime(), 0);
});
